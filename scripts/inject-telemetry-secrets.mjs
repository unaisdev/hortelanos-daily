/**
 * Escribe shared/telemetry.secrets.js desde env / .env (nunca se commitea).
 *
 * Variables:
 *   HORTELANO_SENTRY_DSN          — DSN de Sentry (requerido para activar envío)
 *   HORTELANO_TELEMETRY_ENV       — opcional (p. ej. production / development)
 *   HORTELANO_TELEMETRY_RELEASE   — opcional (p. ej. hortelanos-daily@1.0.1)
 *
 * También acepta SENTRY_DSN como alias.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
const outPath = join(root, 'shared', 'telemetry.secrets.js');

async function loadDotEnv() {
  try {
    const raw = await readFile(join(root, '.env'), 'utf8');
    for (const line of raw.split('\n')) {
      const trimmed = line.trim();
      if (!trimmed || trimmed.startsWith('#')) continue;
      const eq = trimmed.indexOf('=');
      if (eq <= 0) continue;
      const key = trimmed.slice(0, eq).trim();
      let value = trimmed.slice(eq + 1).trim();
      if (
        (value.startsWith('"') && value.endsWith('"'))
        || (value.startsWith("'") && value.endsWith("'"))
      ) {
        value = value.slice(1, -1);
      }
      if (process.env[key] === undefined) process.env[key] = value;
    }
  } catch {
    /* .env opcional */
  }
}

await loadDotEnv();

const dsn = (process.env.HORTELANO_SENTRY_DSN || process.env.SENTRY_DSN || '').trim();
const environment = (process.env.HORTELANO_TELEMETRY_ENV || '').trim();
const release = (process.env.HORTELANO_TELEMETRY_RELEASE || '').trim();

/** @type {Record<string, string>} */
const secrets = {};
if (dsn) secrets.sentryDsn = dsn;
if (environment) secrets.environment = environment;
if (release) secrets.release = release;

const body = [
  '/** Auto-generated by scripts/inject-telemetry-secrets.mjs — DO NOT COMMIT. */',
  `export default ${JSON.stringify(secrets, null, 2)};`,
  '',
].join('\n');

await writeFile(outPath, body, 'utf8');

if (dsn) {
  console.log('inject-telemetry-secrets → shared/telemetry.secrets.js (DSN presente)');
} else {
  console.log('inject-telemetry-secrets → shared/telemetry.secrets.js (vacío; telemetría off)');
}
